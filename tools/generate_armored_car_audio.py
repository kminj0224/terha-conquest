#!/usr/bin/env python3
"""Deterministic offline autocannon burst and shell-impact PCM, separate from MG audio."""
from pathlib import Path
import base64, json, wave
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
RATE=32000
SECONDS=1.0
STEP=.170

def highpass(noise):
    return noise-.90*np.r_[0,noise[:-1]]

def encode(samples, peak):
    samples=np.tanh(samples*1.25)
    samples*=peak/max(.001,float(np.max(np.abs(samples))))
    return np.round(samples*32767).astype('<i2').tobytes()

def burst(variant):
    rng=np.random.default_rng(50750+variant)
    out=np.zeros(round(RATE*SECONDS))
    t=np.arange(round(RATE*.14))/RATE
    for shot in range(5):
        noise=highpass(rng.standard_normal(len(t)))
        crack=noise*np.exp(-t/.0085)*1.08
        snap=np.sin(2*np.pi*(3500*t-6900*t*t))*np.exp(-t/.0035)*.42
        pressure=(np.sin(2*np.pi*(215*t-380*t*t))*.62+
                  np.sin(2*np.pi*105*t)*.28)*np.exp(-t/.027)
        bolt=(highpass(rng.standard_normal(len(t)))*.12+
              np.sin(2*np.pi*1900*t)*.11)*np.exp(-np.maximum(0,t-.023)/.006)*(t>=.023)
        pulse=(crack+snap+pressure+bolt)*min(1,(shot+3)/4)*(1+rng.uniform(-.065,.065))
        for delay,level in [(0,1),(.011,.17),(.029,.075)]:
            at=round((shot*STEP+delay)*RATE);n=min(len(pulse),len(out)-at)
            if n>0:out[at:at+n]+=pulse[:n]*level
    # The last cannon report decays inside the exact 1.0-second firing window.
    out[-192:]*=np.linspace(1,0,192)
    return encode(out,.94)

def impact(variant):
    rng=np.random.default_rng(50850+variant)
    t=np.arange(round(RATE*.23))/RATE
    noise=highpass(rng.standard_normal(len(t)))
    samples=noise*np.exp(-t/.011)*.95
    samples+=(np.sin(2*np.pi*(270*t-430*t*t))*.72+
              np.sin(2*np.pi*115*t)*.34)*np.exp(-t/.047)
    samples+=np.sin(2*np.pi*1740*t)*np.exp(-t/.027)*.17
    for at in [.026,.049,.087]:
        age=np.maximum(0,t-at)
        samples+=noise*np.exp(-age/.006)*(t>=at)*.14
    samples[-320:]*=np.linspace(1,0,320)
    return encode(samples,.88)

def main():
    clips={'armored_autocannon':[burst(v) for v in range(2)],
           'armored_autocannon_hit':[impact(v) for v in range(2)]}
    encoded={name:[base64.b64encode(clip).decode('ascii') for clip in versions] for name,versions in clips.items()}
    target=ROOT/'game/assets/armored-car-audio-data.js'
    target.write_text("'use strict';\n// Generated by tools/generate_armored_car_audio.py, 32000 Hz mono int16 PCM.\nObject.assign(COMBAT_SOUND_BANK,"+json.dumps(encoded,separators=(',',':'))+");\n")
    previews=ROOT/'previews';previews.mkdir(exist_ok=True)
    for name,versions in clips.items():
        with wave.open(str(previews/(name+'.wav')),'wb') as output:
            output.setnchannels(1);output.setsampwidth(2);output.setframerate(RATE);output.writeframes(versions[0])
    print('Generated two exact 1.0 s / 5-round bursts and two 0.23 s shell impacts.')

if __name__=='__main__':main()
