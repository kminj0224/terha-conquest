const assert=require('assert');
module.exports=async function({run}){
 const report=await run(`(async function(){
  const check=(yes,why)=>{if(!yes)throw Error(why)};
  setup();started=true;setAppScreen('game');player=0;busy=false;menuMode=false;
  money[player]=999999;oil[player]=99999;
  const q=cities.find(c=>c.f===player&&c.capital);
  q.level=5;q.airport=true;q.lab=true;q.launcher=true;q.nukeUntil=0;
  strategicResearch[player].ballistic=true;strategicResearch[player].nuclear=true;
  const stock=warheadStock(q);stock.atomic=2;stock.hydrogen=1;syncWarheads(q);
  selectCity(q,true);cityCommandOpen('missiles');
  chooseWarhead(q,'medium',false);
  check($('warheadOptions').textContent.includes('원자폭탄 2개')&&$('warheadOptions').textContent.includes('수소폭탄 1개'),'Picker must show actual typed inventory');
  $('warheadOptions').children[1].children[0].onclick();
  check(strategicTarget?.kind==='nuclearMissile'&&strategicTarget.missileKey==='medium'&&strategicTarget.payload==='hydrogen','Hydrogen missile must begin targeting immediately after selecting payload');
  check(panelOpen===false&&menuMode===false&&$('modal').style.display==='none','Targeting must replace the picker immediately');
  check(armedMissile?.payload==='hydrogen','The missile payload must only be mounted while targeting');
  check(stock.hydrogen===1,'Aiming cannot consume warhead');
  $('selectionAirCancel').onclick();
  check(strategicTarget===null&&armedMissile===null&&armedBomber===null,'Bottom cancel must unload the missile');
  check(stock.hydrogen===1,'Cancelling cannot consume warhead');
  cityCommandOpen('air');chooseWarhead(q,null,true);
  $('warheadOptions').children[0].children[0].onclick();
  check(strategicTarget?.kind==='nuclearBomber'&&strategicTarget.payload==='atomic','Bomber must begin targeting immediately');
  check(armedBomber?.payload==='atomic','Bomber must hold selected payload while aiming');
  cancelAirTarget();
  check(!strategicTarget&&!armedMissile&&!armedBomber,'Cancel must unload bomber');
  check(stock.atomic===2,'Cancelled bombing cannot consume warheads');
  const mock={f:1,type:0,level:1,hp:100,carriedBy:null,tile:q.tile};
  const farTile=tiles.findIndex((_,i)=>distance(i,q.tile)===2);
  const outsideTile=tiles.findIndex((_,i)=>distance(i,q.tile)===3);
  check(farTile>=0&&outsideTile>=0,'Map must include distance 2/3 test fixtures');
  const commando={f:0,type:NAKWOL_COMMANDO,level:1,hp:170,carriedBy:null,tile:q.tile};
  check(TYPES[commando.type].range===2,'Two-hex commando range required');
  mock.tile=farTile;
  check(canCounterattack(commando,mock),'Range-two defender must counterattack a target two hexes away');
  check(rollCounterattack(commando,mock),'Range-two valid retaliation must execute reliably');
  mock.tile=outsideTile;
  check(!canCounterattack(commando,mock),'Range-two defender must not retaliate three hexes away');
  const messages=[],oldToast=toast;
  toast=function(msg){messages.push(msg)};
  const city=cities.find(c=>c.f===player&&c.id!==q.id);
  city.level=5;city.nukeUntil=0;city.airport=false;city.lab=false;city.aa=false;
  check(buildFacility(city,'airport'),'City airport build must succeed');
  check(messages.some(m=>m==='공항이 건설되었습니다.'),'Airport completion toast missing');
  check(buildFacility(city,'lab'),'Science laboratory build must succeed');
  check(messages.some(m=>m==='과학연구소가 건설되었습니다.'),'Lab completion toast missing');
  toast=oldToast;
  // A ready SAM defending an enemy coastal facility must cut actual damage
  // and the damage popup must equal the number subtracted from the HP.
  const enemy=cities.find(c=>atWar(player,c.f));
  check(!!enemy,'An enemy faction must exist');
  const tile=tiles.findIndex((t,i)=>i!==q.tile&&!cityAt(i)&&!unitAt(i)&&!baseAt(i)&&distance(i,q.tile)<=AIR_MISSIONS.fighter.range);
  check(tile>=0,'Need a non-occupied enemy tile in aircraft range');
  const base={id:990099,tile,f:enemy.f,kind:'sam',hp:DEFENSES.sam.hp,remaining:0,lastTick:turn,lastShot:-1};
  missileBases.push(base);
  const hp=base.hp,previous=fx.length;
  check(await airStrike(q,'fighter',tile,true),'Air raid against defended battery should succeed');
  const damageDone=hp-base.hp;
  const expected=Math.round(AIR_MISSIONS.fighter.damage*12*.5);
  check(damageDone===expected,'AA/SAM-protected facility HP must use mitigated damage');
  const popups=fx.slice(previous).filter(e=>e.kind==='blast'&&e.damage!==undefined);
  check(popups.some(e=>e.damage===damageDone),'Air raid popup must display exact post-AA HP damage');
  check(!popups.some(e=>e.damage===AIR_MISSIONS.fighter.damage*12),'Popup must not show unmitigated air damage');
  missileBases=missileBases.filter(v=>v!==base);
  strategicTarget=null;armedMissile=null;armedBomber=null;airTarget=null;
  return{instantMissile:true,instantBomber:true,cancelUnloads:true,range2Counter:true,airportToast:true,samDamage:damageDone,actualPopup:true};
 })()`);
 assert(report.instantMissile&&report.cancelUnloads&&report.actualPopup);
 console.log('PASS v1.10.91 direct nuclear target after mounting, cancel unloads without spent inventory, range-two counterfire, facility built toast, AA/SAM-real popup:',report);
};
